CREATE FUNCTION asura_monitor_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.config_revision = OLD.config_revision THEN
        NEW.config_revision := OLD.config_revision + 1;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER monitor_config_revision BEFORE UPDATE ON monitors
FOR EACH ROW EXECUTE FUNCTION asura_monitor_revision();

CREATE FUNCTION asura_assignment_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE monitors SET config_revision=config_revision+1 WHERE id=NEW.monitor_id;
    ELSIF TG_OP = 'DELETE' THEN
        UPDATE monitors SET config_revision=config_revision+1 WHERE id=OLD.monitor_id;
    ELSE
        UPDATE monitors SET config_revision=config_revision+1 WHERE id IN (OLD.monitor_id,NEW.monitor_id);
    END IF;
    RETURN NULL;
END;
$$;
CREATE TRIGGER monitor_agent_revision AFTER INSERT OR UPDATE OR DELETE ON monitor_agents
FOR EACH ROW EXECUTE FUNCTION asura_assignment_revision();

CREATE FUNCTION asura_agent_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.enabled <> OLD.enabled THEN
        UPDATE monitors SET config_revision=config_revision+1
        WHERE id IN (SELECT monitor_id FROM monitor_agents WHERE agent_id=NEW.id);
    END IF;
    RETURN NULL;
END;
$$;
CREATE TRIGGER agent_enabled_revision AFTER UPDATE OF enabled ON agents
FOR EACH ROW EXECUTE FUNCTION asura_agent_revision();

CREATE FUNCTION asura_proxy_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE monitors SET config_revision=config_revision+1 WHERE proxy_id=NEW.id;
    RETURN NULL;
END;
$$;
CREATE TRIGGER proxy_config_revision AFTER UPDATE ON proxies
FOR EACH ROW EXECUTE FUNCTION asura_proxy_revision();
